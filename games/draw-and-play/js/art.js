    s.e = (x, y, rx, ry, rot, w) => s.fs(s.eP(x, y, rx, ry, rot), w);
    s.r = (x, y, w, h, rad, lw2) => { const p = P(); if (rad) p.roundRect(x, y, w, h, rad); else p.rect(x, y, w, h); return s.fs(p, lw2); };
