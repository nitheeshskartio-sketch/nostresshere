    s.cP = (x, y, r) => { const p = P(); p.arc(x, y, r, 0, TAU); return p; };
    s.eP = (x, y, rx, ry, rot) => { const p = P(); p.ellipse(x, y, rx, ry, rot || 0, 0, TAU); return p; };
